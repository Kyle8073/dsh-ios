#ifndef DSH_WEB_COMPAT_H
#define DSH_WEB_COMPAT_H

// JavaScript injected into the Harness WKWebView before page scripts run.
static const char DSHWebCompatSource[] =
    "// Compatibility for the embedded Harness UI on iOS versions that predate\n"
    "// AbortSignal.any()/timeout(). Existing browser implementations are untouched.\n"
    "(function () {\n"
    "  if (typeof AbortSignal.timeout !== 'function') {\n"
    "    Object.defineProperty(AbortSignal, 'timeout', {\n"
    "      configurable: true,\n"
    "      writable: true,\n"
    "      value: function (milliseconds) {\n"
    "        if (typeof milliseconds !== 'number') throw new TypeError('Timeout must be a number');\n"
    "        if (!Number.isSafeInteger(milliseconds) || milliseconds < 0) {\n"
    "          throw new RangeError('Timeout must be a non-negative safe integer');\n"
    "        }\n"
    "        var controller = new AbortController();\n"
    "        var maximumDelay = 2147483647;\n"
    "        function wait(remaining) {\n"
    "          var delay = Math.min(remaining, maximumDelay);\n"
    "          setTimeout(function () {\n"
    "            if (remaining > maximumDelay) wait(remaining - maximumDelay);\n"
    "            else controller.abort(new DOMException('The operation timed out', 'TimeoutError'));\n"
    "          }, delay);\n"
    "        }\n"
    "        wait(milliseconds);\n"
    "        return controller.signal;\n"
    "      }\n"
    "    });\n"
    "  }\n"
    "\n"
    "  if (typeof AbortSignal.any !== 'function') {\n"
    "    Object.defineProperty(AbortSignal, 'any', {\n"
    "      configurable: true,\n"
    "      writable: true,\n"
    "      value: function (signals) {\n"
    "        var sources = Array.from(signals);\n"
    "        sources.forEach(function (signal) {\n"
    "          if (!signal || typeof signal.aborted !== 'boolean' ||\n"
    "              typeof signal.addEventListener !== 'function' ||\n"
    "              typeof signal.removeEventListener !== 'function') {\n"
    "            throw new TypeError('Expected an iterable of AbortSignals');\n"
    "          }\n"
    "        });\n"
    "        var controller = new AbortController();\n"
    "        var listeners = [];\n"
    "        function abortFrom(signal) {\n"
    "          if (controller.signal.aborted) return;\n"
    "          listeners.forEach(function (item) {\n"
    "            item.signal.removeEventListener('abort', item.listener);\n"
    "          });\n"
    "          listeners.length = 0;\n"
    "          controller.abort(signal.reason);\n"
    "        }\n"
    "        for (var i = 0; i < sources.length; i++) {\n"
    "          if (sources[i].aborted) {\n"
    "            abortFrom(sources[i]);\n"
    "            return controller.signal;\n"
    "          }\n"
    "        }\n"
    "        sources.forEach(function (signal) {\n"
    "          var listener = function () { abortFrom(signal); };\n"
    "          listeners.push({ signal: signal, listener: listener });\n"
    "          signal.addEventListener('abort', listener, { once: true });\n"
    "        });\n"
    "        return controller.signal;\n"
    "      }\n"
    "    });\n"
    "  }\n"
    "})();\n"
;

#endif
